@dataclass
class LauncherState:
    """What the finale may honestly promise about the `actionpulse` command."""

    use_command: bool  # `actionpulse …` is the primary next-steps form
    created: bool  # this wizard run wrote the shim (bare-checkout `make setup`)
    path_hint: bool  # the shim exists but ~/.local/bin is not on PATH


def _ensure_launcher() -> LauncherState:
    """Make sure the global `actionpulse` command exists; report its state.

    install.sh installs the shim on the curl-one-liner path; `make setup` from
    a bare checkout historically did not — so the finale used to advertise a
    command that did not exist. Mirror install.sh here: write the shim only
    when missing (an existing launcher, possibly pointing at another checkout,
    is never overwritten), exec through uv against this checkout.
    """
    if shutil.which("actionpulse"):
        return LauncherState(use_command=True, created=False, path_hint=False)
    if not shutil.which("uv"):
        # No uv to exec through — the module form is the only honest hint.
        return LauncherState(use_command=False, created=False, path_hint=False)
    created = False
    if not LAUNCHER_PATH.exists():
        try:
            LAUNCHER_PATH.parent.mkdir(parents=True, exist_ok=True)
            LAUNCHER_PATH.write_text(
                "#!/bin/sh\n"
                "# ActionPulse launcher — generated by 'actionpulse setup' (mirrors install.sh).\n"
                f'exec uv run --project "{PROJECT_ROOT}" python -m digest_core.cli "$@"\n',
                encoding="utf-8",
            )
            LAUNCHER_PATH.chmod(0o755)
            created = True
        except OSError:
            return LauncherState(use_command=False, created=False, path_hint=False)
    on_path = str(LAUNCHER_PATH.parent) in os.environ.get("PATH", "").split(os.pathsep)
    return LauncherState(use_command=True, created=created, path_hint=not on_path)


def _tilde(path: Path) -> str:
    """Render a path with the home prefix as `~` (display only, §6.2 paths)."""
    text = str(path)
    home = str(Path.home())
    return "~" + text[len(home) :] if text.startswith(home) else text


