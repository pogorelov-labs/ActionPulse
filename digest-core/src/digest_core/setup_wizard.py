def _merge_aliases(aliases: list[str], det: Optional[DetectedEnv]) -> list[str]:
    """Append detected real-name tokens and the machine login to the aliases.

    The email local part is not always name.surname, so the directory RealName
    is the only reliable alias source; the ranker lowercases aliases, so
    Title-case is enough.
    """
    if not det:
        return aliases
    extras: list[str] = []
    for token in (det.first_name, det.last_name):
        if token and len(token) > 1:
            extras.append(token.capitalize())
    if det.login:
        extras.append(det.login)
    merged = list(aliases)
    seen = {a.lower() for a in merged}
    for extra in extras:
        if extra.lower() not in seen:
            merged.append(extra)
            seen.add(extra.lower())
    return merged


def _derive_mm_base_url(webhook: str) -> Optional[str]:
    """``scheme://host`` from a webhook URL (https://mm.corp/hooks/x → https://mm.corp)."""
    try:
        parsed = urlparse(webhook or "")
    except ValueError:
        return None
    if parsed.scheme and parsed.netloc:
        return f"{parsed.scheme}://{parsed.netloc}"
    return None


def _mm_creds_step(webhook: str, existing_pat: str, existing_base: str) -> tuple[str, str]:
    """Optionally collect MM_PAT + MM_BASE_URL (Mattermost ingest / reaction harvest / api-mode
    delivery). Webhook delivery needs neither, so this is opt-in. Non-TTY runs skip prompting and
    preserve existing values (stable line protocol). Returns ``(mm_pat, mm_base_url)`` — existing
    values when kept/skipped, "" when unset. The api-mode delivery CHANNEL is chosen at the corp
    session (it needs the live API to list channels), so it's deliberately not prompted here."""
    console.print(
        "[dim]Optional: a Personal Access Token unlocks MM ingest, reaction harvest, and api-mode"
        " delivery. Webhook delivery (above) needs none.[/]"
    )
    if not sys.stdin.isatty():
        return existing_pat, existing_base
    if not Confirm.ask("[ap.accent.bold]Set a Mattermost PAT now?[/]", default=bool(existing_pat)):
        return existing_pat, existing_base
    mm_pat = _ask_secret("Mattermost PAT", existing=existing_pat)
    default_base = existing_base or _derive_mm_base_url(webhook)
    mm_base_url = _ask("Mattermost base URL", default=default_base, validate=_validate_url)
    return mm_pat, mm_base_url


def _store_step(existing_cfg: dict) -> tuple[bool, Optional[str]]:
    """Optional encrypted-store enable. Returns ``(enabled, key)``.

    This IS ``store init``, in the wizard: it generates (or reuses) the
    DIGEST_STORE_KEY and turns the store on. The key is just a secret — driver
    independent — so the step runs even when the ``store`` extra isn't installed
    yet: the key is saved and the store activates automatically once the driver
    is present. Enabling early is safe because a run with the store on but the
    driver missing degrades-not-drops (``run._persist_to_store`` swallows it), so
    the digest is never broken. Never regenerates an existing key (that would
    orphan the encrypted DB); declining keeps any existing key with the store off.
    """
    import secrets

    from digest_core.store import HAS_SQLCIPHER

    existing_key = os.getenv("DIGEST_STORE_KEY") or None
    default_on = bool((existing_cfg.get("store", {}) or {}).get("enabled")) or bool(existing_key)

    console.print()
    console.rule("[bold]Encrypted message store (optional)[/]", align="left", style="ap.rule")
    console.print(
        "[dim]Persist fetched messages (30d, encrypted at rest) → `search`, `ask`, and the"
        " cross-day Open-loops / Awaiting-your-reply sections (and the MCP server).[/]"
    )
    if not sys.stdin.isatty():
        return default_on, existing_key  # scripted: keep current state, never prompt
    if not Confirm.ask("Enable the encrypted message store?", default=default_on):
        return False, existing_key  # keep the key (don't orphan a prior DB); store stays off

    key = existing_key or secrets.token_hex(32)
    if existing_key:
        console.print("  [ap.ok]✓[/] Store enabled (existing DIGEST_STORE_KEY reused).")
    else:
        console.print("  [ap.ok]✓[/] Store enabled; a new DIGEST_STORE_KEY is written (chmod 600).")
        console.print("  [ap.warn]⚠[/] Keep the key safe — losing it makes the store unreadable.")
    if not HAS_SQLCIPHER:
        console.print(
            "  [ap.warn]⚠[/] The store driver isn't installed yet — run"
            " [bold]uv sync --extra store[/] to activate it (macOS: `brew install sqlcipher"
            " openssl@3` first). The key is saved; until then runs skip store features"
            " (they degrade, never fail)."
        )
    console.print(
        "  [ap.dim]Cross-day sections are opt-in: set store.carryover / store.pending: true"
        " in configs/config.yaml.[/]"
    )
    return True, key


