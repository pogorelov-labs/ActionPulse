def _step(num: int, title: str, hint: Optional[str] = None) -> None:
    console.print()
    console.rule(f"[bold]Step {num}/{TOTAL_STEPS} · {title}[/]", align="left", style="ap.rule")
    if hint:
        console.print(f"[dim]{hint}[/]")


def _ask(
    label: str,
    *,
    default: Optional[str] = None,
    validate: Optional[Callable[[str], Optional[str]]] = None,
) -> str:
    """Prompt until non-empty and valid; Enter accepts the default."""
    while True:
        value = Prompt.ask(f"[ap.accent.bold]{label}[/]", default=default, console=console)
        value = (value or "").strip()
        if not value:
            console.print("  [ap.err]✗[/] The value cannot be empty")
            continue
        error = validate(value) if validate else None
        if error:
            console.print(f"  [ap.err]✗[/] {error}")
            continue
        return value


def _ask_secret(label: str, *, existing: str = "") -> str:
    """Masked prompt with confirmation; Enter keeps the existing value on re-runs."""
    keep_hint = " [dim](Enter — keep current)[/]" if existing else ""
    while True:
        value = Prompt.ask(
            f"[ap.accent.bold]{label}[/]{keep_hint}",
            password=True,
            default="",
            show_default=False,
            console=console,
        ).strip()
        if not value:
            if existing:
                console.print("  [ap.ok]✓[/] Kept the current secret")
                return existing
            console.print("  [ap.err]✗[/] The value cannot be empty")
            continue
        confirm = Prompt.ask(
            "[ap.accent.bold]  Repeat to confirm[/]",
            password=True,
            default="",
            show_default=False,
            console=console,
        ).strip()
        if value == confirm:
            return value
        console.print("  [ap.err]✗[/] The values did not match, try again")


def _ask_ca(existing_cfg: dict, user_upn: str) -> Optional[str]:
    """CA certificate flow: auto-detect -> Keychain export (macOS) -> manual path."""
    verify_ca: Optional[str] = _auto_detect_ca_path(existing_cfg)
    if verify_ca:
        console.print(f"  [ap.ok]✓[/] Auto-detected CA certificate: [bold]{verify_ca}[/]")
        if Confirm.ask("[ap.accent.bold]Use this CA for EWS?[/]", default=True):
            return verify_ca
        verify_ca = None
    else:
        console.print("  [dim]No CA certificate found in the standard paths.[/]")
        if sys.platform == "darwin" and Confirm.ask(
            f"[ap.accent.bold]Export the CA chain from Keychain to "
            f"{DEFAULT_CA_CHAIN_EXPORT_PATH}?[/]",
            default=True,
        ):
            default_alias = _guess_default_ca_alias(user_upn)
            default_intermediate_alias = _guess_default_intermediate_ca_alias(user_upn)
            cert_name = _ask(
                "  Root CA certificate name in Keychain",
                default=default_alias or "AO Raiffeisenbank RootCA",
            )
            intermediate_default = default_intermediate_alias or ""
            intermediate_hint = (
                f"(Enter — {intermediate_default})" if intermediate_default else "(Enter — skip)"
            )
            intermediate_alias: Optional[str] = (
                Prompt.ask(
                    f"[ap.accent.bold]  Intermediate CA name[/] [dim]{intermediate_hint}[/]",
                    default=intermediate_default,
                    show_default=False,
                    console=console,
                ).strip()
                or None
            )

            with console.status(
                "[ap.accent]Exporting the CA chain from Keychain…", spinner=SPINNER
            ):
                ok, cert_count = _export_ca_chain_from_keychain(
                    cert_name,
                    DEFAULT_CA_CHAIN_EXPORT_PATH,
                    intermediate_alias=intermediate_alias,
                )
            if ok:
                verify_ca = str(DEFAULT_CA_CHAIN_EXPORT_PATH)
                console.print(f"  [ap.ok]✓[/] CA chain exported: {verify_ca} ({cert_count} cert)")
            else:
                console.print("  [ap.warn]⚠[/] Failed to export the CA chain from Keychain.")

    if not verify_ca and Confirm.ask(
        "[ap.accent.bold]Provide a CA certificate path manually?[/]", default=False
    ):
        verify_ca = _ask("  Path to the CA certificate (.pem)")
        if verify_ca and not Path(verify_ca).expanduser().exists():
            console.print(
                f"  [ap.warn]⚠[/] File not found: {verify_ca} (keeping the path as given)"
            )
        elif verify_ca:
            verify_ca = str(Path(verify_ca).expanduser())
    return verify_ca


def _summary_table(
    env_values: dict[str, str],
    verify_ca: Optional[str],
    report_language: str = "en",
    ews_login: Optional[str] = None,
) -> Table:
    table = Table(box=box.SIMPLE, show_header=False, pad_edge=False)
    table.add_column(style="dim", min_width=18)
    table.add_column()
    table.add_row("Email (UPN)", env_values["EWS_USER_UPN"])
    if ews_login:
        table.add_row("EWS login (NTLM)", ews_login)
    table.add_row("EWS endpoint", env_values["EWS_ENDPOINT"])
    table.add_row("EWS password", _mask_secret(env_values["EWS_PASSWORD"], show_tail=0))
    table.add_row("LLM endpoint", env_values["LLM_ENDPOINT"])
    table.add_row("LLM token", _mask_secret(env_values["LLM_TOKEN"]))
    table.add_row("MM webhook", env_values["MM_WEBHOOK_URL"])
    table.add_row("Report language", report_language)
    table.add_row("CA certificate", verify_ca or "[dim]— (system trust store)[/]")
    return table


def _print_detection(det: DetectedEnv) -> None:
    if not det.has_findings():
        console.print("[dim]Autodetection: nothing useful found — asking everything explicitly.[/]")
        return
    lines = "\n".join(f"[ap.ok]✓[/] {escape(note)}" for note in det.notes)
    console.print(
        Panel(
            lines,
            title="[bold]Autodetection[/]",
            box=box.ROUNDED,
            border_style="ap.rule",
            expand=False,
        )
    )


def _merge_aliases(aliases: list[str], det: Optional[DetectedEnv]) -> list[str]:
    """Append detected real-name tokens and the machine login to the aliases.

    The email local part is not always name.surname, so the directory RealName
    is the only reliable alias source; the ranker lowercases aliases, so
    Title-case is enough.
    """
    if not det:
        return aliases
    extras: list[str] = []
    for token in (det.first_name, det.last_name):
        if token and len(token) > 1:
            extras.append(token.capitalize())
    if det.login:
        extras.append(det.login)
    merged = list(aliases)
    seen = {a.lower() for a in merged}
    for extra in extras:
        if extra.lower() not in seen:
            merged.append(extra)
            seen.add(extra.lower())
    return merged


