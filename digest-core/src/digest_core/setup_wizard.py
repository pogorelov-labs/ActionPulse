def _ask(
    label: str,
    *,
    default: Optional[str] = None,
    validate: Optional[Callable[[str], Optional[str]]] = None,
) -> str:
    """Prompt until non-empty and valid; Enter accepts the default."""
    while True:
        value = Prompt.ask(f"[ap.accent.bold]{label}[/]", default=default, console=console)
        value = (value or "").strip()
        if not value:
            console.print("  [ap.err]✗[/] The value cannot be empty")
            continue
        error = validate(value) if validate else None
        if error:
            console.print(f"  [ap.err]✗[/] {error}")
            continue
        return value


def _ask_secret(label: str, *, existing: str = "") -> str:
    """Masked single-entry prompt; Enter keeps the existing value on re-runs.

    No confirm-twice: tokens/passwords are pasted, not typed, so repeating is
    friction, not safety. Correctness is verified instead by the live connection
    checks at the end of setup (LLM gateway + Mattermost)."""
    keep_hint = " [dim](Enter — keep current)[/]" if existing else ""
    while True:
        value = Prompt.ask(
            f"[ap.accent.bold]{label}[/]{keep_hint}",
            password=True,
            default="",
            show_default=False,
            console=console,
        ).strip()
        if value:
            return value
        if existing:
            console.print("  [ap.ok]✓[/] Kept the current secret")
            return existing
        console.print("  [ap.err]✗[/] The value cannot be empty")


def _ask_ca(existing_cfg: dict, user_upn: str) -> Optional[str]:
    """CA certificate flow: auto-detect -> Keychain export (macOS) -> manual path."""
    verify_ca: Optional[str] = _auto_detect_ca_path(existing_cfg)
    if verify_ca:
        console.print(f"  [ap.ok]✓[/] Auto-detected CA certificate: [bold]{verify_ca}[/]")
        if Confirm.ask("[ap.accent.bold]Use this CA for EWS?[/]", default=True):
            return verify_ca
        verify_ca = None
    else:
        console.print("  [dim]No CA certificate found in the standard paths.[/]")
        if sys.platform == "darwin" and Confirm.ask(
            f"[ap.accent.bold]Export the CA chain from Keychain to "
            f"{DEFAULT_CA_CHAIN_EXPORT_PATH}?[/]",
            default=True,
        ):
            default_alias = _guess_default_ca_alias(user_upn)
            default_intermediate_alias = _guess_default_intermediate_ca_alias(user_upn)
            cert_name = _ask(
                "  Root CA certificate name in Keychain",
                default=default_alias or "AO Raiffeisenbank RootCA",
            )
            intermediate_default = default_intermediate_alias or ""
            intermediate_hint = (
                f"(Enter — {intermediate_default})" if intermediate_default else "(Enter — skip)"
            )
            intermediate_alias: Optional[str] = (
                Prompt.ask(
                    f"[ap.accent.bold]  Intermediate CA name[/] [dim]{intermediate_hint}[/]",
                    default=intermediate_default,
                    show_default=False,
                    console=console,
                ).strip()
                or None
            )

            with console.status(
                "[ap.accent]Exporting the CA chain from Keychain…", spinner=SPINNER
            ):
                ok, cert_count = _export_ca_chain_from_keychain(
                    cert_name,
                    DEFAULT_CA_CHAIN_EXPORT_PATH,
                    intermediate_alias=intermediate_alias,
                )
            if ok:
                verify_ca = str(DEFAULT_CA_CHAIN_EXPORT_PATH)
                console.print(f"  [ap.ok]✓[/] CA chain exported: {verify_ca} ({cert_count} cert)")
            else:
                console.print("  [ap.warn]⚠[/] Failed to export the CA chain from Keychain.")

    if not verify_ca and Confirm.ask(
        "[ap.accent.bold]Provide a CA certificate path manually?[/]", default=False
    ):
        verify_ca = _ask("  Path to the CA certificate (.pem)")
        if verify_ca and not Path(verify_ca).expanduser().exists():
            console.print(
                f"  [ap.warn]⚠[/] File not found: {verify_ca} (keeping the path as given)"
            )
        elif verify_ca:
            verify_ca = str(Path(verify_ca).expanduser())
    return verify_ca


def _dm_scope_label(scope: str) -> str:
    """Short human label for a DM scope (summary/header rendering)."""
    return {
        "off": "Off",
        "own_posts_only": "My posts only",
        "selected": "Selected partners",
        "all": "All DMs",
    }.get(scope, scope)


def _dm_summary_value(scope: str, allowlist: list[str]) -> str:
    """Summary-row text for the DM scope (+ partner count under 'selected')."""
    label = _dm_scope_label(scope)
    if scope == "selected":
        n = len(allowlist)
        if n == 0:
            return f"{label} [ap.warn](0 partners → effectively OFF)[/]"
        return f"{label} ({n} partner{'s' if n != 1 else ''})"
    return label


