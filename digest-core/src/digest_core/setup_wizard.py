def _read_existing_env() -> dict[str, str]:
    """Read existing env file into dict."""
    values: dict[str, str] = {}
    if not ENV_PATH.exists():
        return values
    for line in ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" in line:
            key, _, val = line.partition("=")
            values[key.strip()] = val.strip()
    return values


def _read_existing_config() -> dict:
    """Read existing user config.yaml into dict.

    Deliberately ignores config.example.yaml: its placeholder values
    (owa.corp-domain.ru, …) would otherwise shadow the defaults derived
    from the user's email on a fresh install.
    """
    if not CONFIG_USER.exists():
        return {}
    with open(CONFIG_USER, "r", encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def _derive_from_email(email: str) -> dict[str, str]:
    """Derive EWS fields from corp email address.

    ivan.petrov@megacorp.ru ->
        user_login: ivan.petrov   (FALLBACK only — see _resolve_ews_login)
        user_domain: megacorp.ru
        default_ews_endpoint: https://owa.megacorp.ru/EWS/Exchange.asmx
        aliases: ["Ivan", "Petrov", "ivan.petrov@megacorp.ru", "ivan.petrov"]

    NOTE: ``user_login`` here is the email local part and is only a last-resort
    fallback. EWS NTLM authenticates with the *machine* (AD) login from
    ``whoami`` — e.g. "ruapgr2" — which routinely differs from the email local
    part ("ruslan.pogorelov"). The wizard overrides it via _resolve_ews_login.
    """
    login, _, domain = email.partition("@")
    parts = re.split(r"[._-]", login)
    aliases = [p.capitalize() for p in parts if len(p) > 1]
    aliases.extend([email, login])

    return {
        "user_login": login,
        "user_domain": domain,
        "default_ews_endpoint": f"https://owa.{domain}/EWS/Exchange.asmx",
        "aliases": aliases,
    }


def _resolve_ews_login(
    existing_login: Optional[str], machine_login: Optional[str], email_local_part: str
) -> str:
    """EWS NTLM login: existing config wins, else the machine (AD) login from
    ``whoami`` (the correct NTLM identity, e.g. "ruapgr2"), else the email
    local part as a last resort."""
    return (existing_login or "").strip() or (machine_login or "").strip() or email_local_part


def _write_env_file(values: dict[str, str], ntlm_login_hint: Optional[str] = None) -> Path:
    """Write env file in systemd-compatible KEY=value format.

    ntlm_login_hint: detected machine (AD) login when it differs from the
    email local part — written as a commented override so the fix is at hand
    exactly where the user looks after an EWS auth failure.
    """
    ENV_DIR.mkdir(parents=True, exist_ok=True)

    lines = [
        "# ActionPulse environment — generated by 'actionpulse setup'",
        "# Format: KEY=value (no export, no quotes) — works with systemd and bash",
        "",
        "# === Required ===",
        "",
    ]
    required_keys = [
        "EWS_PASSWORD",
        "EWS_USER_UPN",
        "EWS_ENDPOINT",
        "LLM_TOKEN",
        "LLM_ENDPOINT",
        "MM_WEBHOOK_URL",
    ]
    for key in required_keys:
        if key in values:
            lines.append(f"{key}={values[key]}")
    lines.append("")
    lines.append("# === Optional ===")
    lines.append("")
    # Store key + MM credentials when configured (secrets; ENV-only, never YAML). Written
    # here so re-running setup preserves them rather than dropping them on the rewrite.
    for key in ("DIGEST_STORE_KEY", "MM_PAT", "MM_BASE_URL"):
        if key in values:
            lines.append(f"{key}={values[key]}")
    lines.append("# DIGEST_CONFIG_PATH=/path/to/config.yaml")
    lines.append("# DIGEST_OUT_DIR=/custom/out")
    lines.append("# DIGEST_STATE_DIR=/custom/state")
    lines.append("# DIGEST_LOG_LEVEL=INFO")
    if ntlm_login_hint:
        lines.append("")
        lines.append("# EWS NTLM auth uses user_login@user_domain from config.yaml.")
        lines.append("# Override it here if EWS rejects the detected machine login:")
        lines.append(f"# EWS_USER_LOGIN={ntlm_login_hint}")
    lines.append("")

    ENV_PATH.write_text("\n".join(lines), encoding="utf-8")
    os.chmod(ENV_PATH, 0o600)
    return ENV_PATH


def _write_config_yaml(
    user_upn: str,
    ews_endpoint: str,
    llm_endpoint: str,
    derived: dict[str, str],
    verify_ca: Optional[str],
    report_language: str = "en",
    acknowledged_private: bool = False,
    dm_scope: str = "off",
    dm_allowlist: Optional[list[str]] = None,
    dm_consent_acknowledged: bool = False,
    dm_consent_acknowledged_at: Optional[str] = None,
    store_enabled: bool = False,
) -> Path:
    """Generate configs/config.yaml from example with user values applied."""
    if not CONFIG_EXAMPLE.exists():
        raise FileNotFoundError(f"Config example not found: {CONFIG_EXAMPLE}")

    with open(CONFIG_EXAMPLE, "r", encoding="utf-8") as f:
        config = yaml.safe_load(f)

    # Apply user values
    ews = config.get("ews", {})
    ews["endpoint"] = ews_endpoint
    ews["user_upn"] = user_upn
    ews["user_login"] = derived["user_login"]
    ews["user_domain"] = derived["user_domain"]
    ews["user_aliases"] = derived["aliases"]
    if verify_ca:
        ews["verify_ca"] = verify_ca
    else:
        ews.pop("verify_ca", None)
    config["ews"] = ews

    llm = config.get("llm", {})
    llm["endpoint"] = llm_endpoint
    config["llm"] = llm

    report = config.get("report", {}) or {}
    report["language"] = report_language
    config["report"] = report

    # D4: persist the private-target acknowledgement so the deliver path knows
    # whether to warn. Other deliver.mattermost keys (from the example) survive.
    deliver = config.get("deliver", {}) or {}
    mattermost = deliver.get("mattermost", {}) or {}
    mattermost["acknowledged_private"] = bool(acknowledged_private)
    deliver["mattermost"] = mattermost
    config["deliver"] = deliver

    # DM-scope privacy ladder (LVL4). The example block carries the defaults
    # (off / empty / no consent); thread the wizard's choices over them. Consent
    # fields are only ever True alongside a timestamp — and a consent scope
    # ('selected'/'all') is never written without that ack (the wizard falls
    # back to 'off' on decline), so the result stays loadable by Config().
    mm_source = config.get("mm_source", {}) or {}
    mm_source["dm_scope"] = dm_scope
    mm_source["dm_allowlist"] = list(dm_allowlist or [])
    mm_source["dm_consent_acknowledged"] = bool(dm_consent_acknowledged)
    mm_source["dm_consent_acknowledged_at"] = dm_consent_acknowledged_at
    # A chosen DM scope is inert unless MM ingest is enabled — flip the master switch so
    # the consent the user just gave is not a silent no-op. (Ingest still needs MM_PAT in
    # env and running with `--sources ews,mm`; the wizard surfaces that after the DM step.)
    if dm_scope != "off":
        mm_source["enabled"] = True
    config["mm_source"] = mm_source

    # Encrypted store: the example ships `store:` commented out, so set the block here when
    # the wizard enabled it (Config() merges `store` unconditionally → this enabled wins).
    if store_enabled:
        store_block = config.get("store", {}) or {}
        store_block["enabled"] = True
        config["store"] = store_block

    CONFIG_USER.parent.mkdir(parents=True, exist_ok=True)
    with open(CONFIG_USER, "w", encoding="utf-8") as f:
        yaml.dump(config, f, default_flow_style=False, allow_unicode=True, sort_keys=False)
    return CONFIG_USER


def _test_mm_webhook(url: str, timeout: float = 5.0) -> tuple[bool, str]:
    """POST a fixed test message to the Mattermost incoming webhook.

    The only endpoint verifiable from outside the corp perimeter (ADR-012:
    Mattermost is reachable from everywhere). Returns (ok, detail); the URL
    is never logged.
    """
    try:
        import httpx

        resp = httpx.post(
            url,
            json={"text": "⌁ ActionPulse: webhook verified — setup complete."},
            timeout=timeout,
        )
        if resp.status_code == 200:
            return True, "delivered"
        return False, f"HTTP {resp.status_code}"
    except Exception as exc:  # noqa: BLE001 — any network failure is a soft result
        return False, type(exc).__name__


def _test_llm(endpoint: str, token: str, *, verify=True, timeout: float = 10.0) -> tuple[bool, str]:
    """Probe the LLM gateway: GET ``<base>/models`` with the bearer token —
    generation-free + auth-checked. Returns (ok, detail); the token is never
    logged. The gateway is corp-only (ADR-012), so outside the perimeter this
    reports unreachable, which is expected, not an error."""
    try:
        import httpx

        base = endpoint.rstrip("/")
        for suffix in ("/chat/completions", "/completions"):
            if base.endswith(suffix):
                base = base[: -len(suffix)]
                break
        resp = httpx.get(
            f"{base}/models",
            headers={"Authorization": f"Bearer {token}"},
            timeout=timeout,
            verify=verify,
        )
        if resp.status_code == 200:
            return True, "reachable, token accepted"
        if resp.status_code in (401, 403):
            return False, f"token rejected (HTTP {resp.status_code})"
        if resp.status_code in (404, 405):
            return True, "endpoint reachable (token not confirmed — no /models)"
        return False, f"HTTP {resp.status_code}"
    except Exception as exc:  # noqa: BLE001 — any network failure is a soft result
        return False, type(exc).__name__


def _test_mm_pat(
    base_url: str, pat: str, *, verify=True, timeout: float = 10.0
) -> tuple[bool, str]:
    """Probe the Mattermost API: GET ``/api/v4/users/me`` with the PAT. Returns
    (ok, '@username' | detail); the token is never logged. Mattermost is
    reachable from anywhere (ADR-012)."""
    try:
        import httpx

        resp = httpx.get(
            f"{base_url.rstrip('/')}/api/v4/users/me",
            headers={"Authorization": f"Bearer {pat}"},
            timeout=timeout,
            verify=verify,
        )
        if resp.status_code == 200:
            username = (resp.json() or {}).get("username", "")
            return True, (f"@{username}" if username else "token accepted")
        if resp.status_code in (401, 403):
            return False, f"token rejected (HTTP {resp.status_code})"
        return False, f"HTTP {resp.status_code}"
    except Exception as exc:  # noqa: BLE001 — any network failure is a soft result
        return False, type(exc).__name__


