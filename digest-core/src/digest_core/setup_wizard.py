def run_setup(no_autodetect: bool = False) -> None:
    """Interactive setup: 7 questions, 0 text editors, auto-detected defaults."""
    try:
        _banner()

        det: Optional[DetectedEnv] = None
        existing_env = _read_existing_env()
        if not no_autodetect and not (
            existing_env.get("EWS_USER_UPN") and existing_env.get("EWS_ENDPOINT")
        ):
            with console.status(
                "[ap.accent]Autodetecting: login, name, Keychain, network domains…", spinner=SPINNER
            ):
                det = detect_environment()
            _print_detection(det)

        if _run_setup_flow(det=det, force_ask=False):
            return
        console.print()
        console.rule("[bold]Change answers[/]", align="left", style="ap.rule.attn")
        console.print(
            "[dim]Going through the questions again; detected values are the defaults.[/]"
        )
        if not _run_setup_flow(det=det, force_ask=True):
            console.print("[ap.warn]⚠ Cancelled — no files were changed.[/]")
            raise typer.Exit(1)
    except (KeyboardInterrupt, EOFError):
        console.print("\n[ap.warn]⚠ Setup interrupted — no files were changed.[/]")
        raise typer.Exit(130)


def _run_setup_flow(det: Optional[DetectedEnv] = None, force_ask: bool = False) -> bool:
    """One pass over the questions; True when files were written, False on decline."""
    # Read existing values for defaults
    existing_env = _read_existing_env()
    existing_cfg = _read_existing_config()
    if existing_env:
        console.print(
            "[dim]Existing configuration found — current values are "
            "pre-filled as the default answers.[/]"
        )

    det_upn = det.best_upn if det else None
    det_host = det.ews_host if det else None

    # ── 1. Corp email ──
    _step(1, "Corporate email", "Used to derive the EWS endpoint, login and aliases.")
    default_upn = (
        existing_env.get("EWS_USER_UPN")
        or existing_cfg.get("ews", {}).get("user_upn")
        or det_upn
        or None
    )
    if (
        not force_ask
        and det_upn
        and det is not None
        and det.upn_confidence == CONF_HIGH
        and not existing_env.get("EWS_USER_UPN")
        and _validate_email(det_upn) is None
    ):
        user_upn = det_upn
        console.print(
            f"  [ap.ok]✓[/] Automatic: [bold]{user_upn}[/] "
            f'[dim](Keychain + name + domain; to change it, answer "n" at the final confirmation)[/]'
        )
    else:
        user_upn = _ask(
            "Email (login@corp-domain.ru)", default=default_upn, validate=_validate_email
        )

    derived = _derive_from_email(user_upn)
    derived["aliases"] = _merge_aliases(derived["aliases"], det)

    # EWS NTLM login = the machine/AD login (whoami: "ruapgr2"), NOT the email
    # local part ("ruslan.pogorelov"). whoami is cheap and reliable even with
    # autodetection off; fall back to a prompt only if it is unavailable.
    machine_login = _machine_login()
    existing_login = existing_cfg.get("ews", {}).get("user_login") or existing_env.get(
        "EWS_USER_LOGIN"
    )
    if existing_login or machine_login:
        derived["user_login"] = _resolve_ews_login(
            existing_login, machine_login, derived["user_login"]
        )
    else:
        derived["user_login"] = _ask(
            "EWS login (NTLM username, e.g. ruapgr2)", default=derived["user_login"]
        )
    if machine_login and machine_login.lower() not in [a.lower() for a in derived["aliases"]]:
        derived["aliases"].append(machine_login)

    console.print(
        f"  [ap.ok]✓[/] EWS login [bold]{derived['user_login']}[/] "
        f"[dim](NTLM · machine login)[/] · domain [bold]{derived['user_domain']}[/]"
    )
    console.print(f"  [ap.ok]✓[/] email (UPN) [bold]{user_upn}[/]")
    console.print(f"  [ap.ok]✓[/] aliases: [dim]{', '.join(derived['aliases'])}[/]")

    # ── 2. EWS endpoint ──
    _step(2, "Exchange (EWS)", "Address of the corporate EWS mail service.")
    detected_ews = f"https://{det_host}/EWS/Exchange.asmx" if det_host else None
    default_ews = (
        existing_env.get("EWS_ENDPOINT")
        or existing_cfg.get("ews", {}).get("endpoint")
        or detected_ews
        or derived["default_ews_endpoint"]
    )
    if (
        not force_ask
        and detected_ews
        and det is not None
        and det.ews_endpoint_verified
        and not existing_env.get("EWS_ENDPOINT")
        and not existing_cfg.get("ews", {}).get("endpoint")
    ):
        ews_endpoint = detected_ews
        console.print(
            f"  [ap.ok]✓[/] Automatic: [bold]{ews_endpoint}[/] [dim](host from Keychain, DNS ✓)[/]"
        )
    else:
        ews_endpoint = _ask("EWS endpoint URL", default=default_ews, validate=_validate_url)

    # ── 3. EWS password ──
    _step(3, "Exchange password", "Stored locally only: ~/.config/actionpulse/env, chmod 600.")
    ews_password = _ask_secret("EWS password", existing=existing_env.get("EWS_PASSWORD", ""))

    # ── 4. LLM endpoint ──
    _step(4, "LLM Gateway", "Corporate LLM gateway (reachable only from the corp network).")
    default_llm = (
        existing_env.get("LLM_ENDPOINT") or existing_cfg.get("llm", {}).get("endpoint") or None
    )
    llm_endpoint = _ask("LLM Gateway endpoint URL", default=default_llm, validate=_validate_url)

    # ── 5. LLM token ──
    _step(5, "LLM Gateway token", "Bearer token; never written to logs or configs in plain form.")
    llm_token = _ask_secret("LLM token (Bearer)", existing=existing_env.get("LLM_TOKEN", ""))

    # ── 6. Mattermost webhook ──
    _step(6, "Mattermost", "Incoming webhook of the channel that receives the digest.")
    default_mm = existing_env.get("MM_WEBHOOK_URL") or None
    mm_webhook = _ask("Mattermost webhook URL", default=default_mm, validate=_validate_url)

    # ── 7. Report language ──
    _step(7, "Report language", "Digest output language; everything else stays English.")
    default_lang = existing_cfg.get("report", {}).get("language") or "en"
    if sys.stdin.isatty():
        report_language = choose(
            "Report language",
            # i18n-ok: a language names itself in its own language
            [("en", "English (default)"), ("ru", "Russian · Русский")],
            default_index=0 if default_lang == "en" else 1,
            console=console,
        )
    else:
        # Piped/scripted runs keep the line protocol stable.
        report_language = Prompt.ask(
            "[ap.accent.bold]Report language[/]",
            choices=["en", "ru"],
            default=default_lang,
            console=console,
        )

    # ── Optional: CA certificate (auto-first) ──
    console.print()
    console.rule("[bold]TLS · corporate CA[/]", align="left", style="ap.rule")
    console.print(
        "[dim]Needed when corp certificates are not trusted by the system (EWS behind a proxy).[/]"
    )
    verify_ca = _ask_ca(existing_cfg, user_upn)

    # ── Review before writing ──
    env_values = {
        "EWS_PASSWORD": ews_password,
        "EWS_USER_UPN": user_upn,
        "EWS_ENDPOINT": ews_endpoint,
        "LLM_TOKEN": llm_token,
        "LLM_ENDPOINT": llm_endpoint,
        "MM_WEBHOOK_URL": mm_webhook,
    }
    console.print()
    console.print(
        Panel(
            _summary_table(env_values, verify_ca, report_language, derived["user_login"]),
            title="[bold]Review the values[/]",
            box=box.ROUNDED,
            border_style="ap.accent",
            expand=False,
        )
    )
    if not Confirm.ask("[ap.accent.bold]Save the configuration?[/]", default=True):
        return False

    # ── Write files ──
    # user_login is now the machine/AD login. If the email local part differs,
    # leave it as a commented alternative in case NTLM wants that form instead.
    email_local_part = user_upn.partition("@")[0]
    ntlm_hint = (
        email_local_part if email_local_part.lower() != derived["user_login"].lower() else None
    )

    with console.status("[ap.accent]Writing files…", spinner=SPINNER):
        env_path = _write_env_file(env_values, ntlm_login_hint=ntlm_hint)
        config_path = _write_config_yaml(
            user_upn=user_upn,
            ews_endpoint=ews_endpoint,
            llm_endpoint=llm_endpoint,
            derived=derived,
            verify_ca=verify_ca,
            report_language=report_language,
        )
    console.print(f"  [ap.ok]✓[/] {env_path}  [dim](chmod 600)[/]")
    console.print(f"  [ap.ok]✓[/] {config_path}")

    # ── Load env into current process ──
    for key, val in env_values.items():
        os.environ[key] = val

    # ── Live check: Mattermost is the one endpoint reachable from anywhere ──
    # TTY-gated so scripted/piped runs keep a stable answer protocol.
    if sys.stdin.isatty() and Confirm.ask(
        "[ap.accent.bold]Send a test message to Mattermost?[/]", default=True
    ):
        with console.status("[ap.accent]Checking the webhook…", spinner=SPINNER):
            mm_ok, mm_detail = _test_mm_webhook(mm_webhook)
        if mm_ok:
            console.print("  [ap.ok]✓[/] Webhook works — the test message is in the channel")
        else:
            console.print(
                f"  [ap.warn]⚠[/] Webhook did not respond ({mm_detail}). Mattermost is reachable even "
                f"outside the corp network — check the URL (re-run setup to fix)."
            )

    # ── Summary: next steps speak `actionpulse`, never the module form ──
    launcher = _ensure_launcher()
    if launcher.created:
        console.print(
            f"  [ap.ok]✓[/] Command installed: [bold]actionpulse[/]  [ap.dim]({LAUNCHER_PATH})[/]"
        )
    console.print()
    console.print(
        Panel(
            _next_steps_text(launcher),
            title=gradient_text("⌁ Done"),
            box=box.ROUNDED,
            border_style="ap.ok",
            padding=(1, 2),
            expand=False,
        )
    )
    return True
